namespace Nop.Plugin.CW.ThemeCore.Domain.BrandDesigner;

/// <summary>
/// A generated brand palette — the six accent tokens CW.ThemeCore exposes as CSS custom properties.
/// Colour values are hex WITHOUT a leading '#', matching <c>CwThemeSettings</c>.
/// </summary>
public class BrandPalette
{
    public string PrimaryColor { get; set; }
    public string PrimaryTintColor { get; set; }
    public string SuccessColor { get; set; }
    public string DangerColor { get; set; }
    public string WarningColor { get; set; }
    public string DarkColor { get; set; }
}
